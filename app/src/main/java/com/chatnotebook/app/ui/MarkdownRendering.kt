package com.chatnotebook.app.ui

import android.graphics.Typeface
import android.text.Spannable
import android.text.SpannableStringBuilder
import android.text.Spanned
import android.text.style.ForegroundColorSpan
import android.text.style.RelativeSizeSpan
import android.text.style.StrikethroughSpan
import android.text.style.StyleSpan
import androidx.compose.ui.graphics.Color as ComposeColor
import androidx.compose.ui.text.AnnotatedString
import androidx.compose.ui.text.SpanStyle
import androidx.compose.ui.text.buildAnnotatedString
import androidx.compose.ui.text.font.FontStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.TextDecoration
import androidx.compose.ui.text.withStyle
import androidx.compose.ui.unit.sp

internal enum class MarkdownBlockKind { Heading1, Heading2, Heading3, Quote, Bullet, Paragraph }

internal data class MarkdownBlock(val kind: MarkdownBlockKind, val text: String)

internal data class MarkdownRun(
    val text: String,
    val bold: Boolean = false,
    val italic: Boolean = false,
    val strike: Boolean = false,
    val color: Int? = null,
)

/**
 * Minimal Markdown reader for the document generated by this app: headings, quotes,
 * bullets and inline emphasis/color. Unknown syntax stays as plain text.
 */
internal object MarkdownParser {
    private const val SPAN_OPEN = "<span"
    private const val SPAN_CLOSE = "</span>"
    private val colorPattern = Regex("#[0-9A-Fa-f]{6}")

    fun blocks(markdown: String): List<MarkdownBlock> {
        val result = mutableListOf<MarkdownBlock>()
        val paragraph = StringBuilder()
        fun flushParagraph() {
            if (paragraph.isNotEmpty()) {
                result += MarkdownBlock(MarkdownBlockKind.Paragraph, paragraph.toString())
                paragraph.clear()
            }
        }
        markdown.replace("\r\n", "\n").split('\n').forEach { raw ->
            val line = raw.trimEnd()
            when {
                line.isBlank() -> flushParagraph()
                line.startsWith("### ") -> {
                    flushParagraph()
                    result += MarkdownBlock(MarkdownBlockKind.Heading3, line.removePrefix("### ").trim())
                }
                line.startsWith("## ") -> {
                    flushParagraph()
                    result += MarkdownBlock(MarkdownBlockKind.Heading2, line.removePrefix("## ").trim())
                }
                line.startsWith("# ") -> {
                    flushParagraph()
                    result += MarkdownBlock(MarkdownBlockKind.Heading1, line.removePrefix("# ").trim())
                }
                line.startsWith("> ") -> {
                    flushParagraph()
                    result += MarkdownBlock(MarkdownBlockKind.Quote, line.removePrefix("> ").trim())
                }
                line.startsWith("- ") -> {
                    flushParagraph()
                    result += MarkdownBlock(MarkdownBlockKind.Bullet, line.removePrefix("- ").trim())
                }
                line.startsWith("* ") -> {
                    flushParagraph()
                    result += MarkdownBlock(MarkdownBlockKind.Bullet, line.removePrefix("* ").trim())
                }
                else -> {
                    if (paragraph.isNotEmpty()) paragraph.append('\n')
                    paragraph.append(line)
                }
            }
        }
        flushParagraph()
        return result
    }

    fun runs(text: String): List<MarkdownRun> {
        val result = mutableListOf<MarkdownRun>()
        parse(text, MarkdownRun(""), result)
        return result
    }

    private fun parse(text: String, style: MarkdownRun, out: MutableList<MarkdownRun>) {
        var index = 0
        var plainStart = 0
        while (index < text.length) {
            when {
                text.startsWith(SPAN_OPEN, index) -> {
                    val tagEnd = text.indexOf('>', index)
                    val close = if (tagEnd < 0) -1 else text.indexOf(SPAN_CLOSE, tagEnd + 1)
                    if (tagEnd < 0 || close < 0) {
                        index++
                    } else {
                        flush(text, plainStart, index, style, out)
                        val color = colorPattern.find(text.substring(index, tagEnd))?.value?.let(::parseColor)
                        parse(
                            text.substring(tagEnd + 1, close),
                            style.copy(color = color ?: style.color),
                            out,
                        )
                        index = close + SPAN_CLOSE.length
                        plainStart = index
                    }
                }
                text.startsWith("**", index) -> {
                    val close = text.indexOf("**", index + 2)
                    if (close <= index + 2) {
                        index++
                    } else {
                        flush(text, plainStart, index, style, out)
                        parse(text.substring(index + 2, close), style.copy(bold = true), out)
                        index = close + 2
                        plainStart = index
                    }
                }
                text.startsWith("~~", index) -> {
                    val close = text.indexOf("~~", index + 2)
                    if (close <= index + 2) {
                        index++
                    } else {
                        flush(text, plainStart, index, style, out)
                        parse(text.substring(index + 2, close), style.copy(strike = true), out)
                        index = close + 2
                        plainStart = index
                    }
                }
                text[index] == '*' -> {
                    val close = text.indexOf('*', index + 1)
                    if (close <= index + 1) {
                        index++
                    } else {
                        flush(text, plainStart, index, style, out)
                        parse(text.substring(index + 1, close), style.copy(italic = true), out)
                        index = close + 1
                        plainStart = index
                    }
                }
                else -> index++
            }
        }
        flush(text, plainStart, text.length, style, out)
    }

    private fun flush(
        text: String,
        start: Int,
        end: Int,
        style: MarkdownRun,
        out: MutableList<MarkdownRun>,
    ) {
        if (end > start) out += style.copy(text = text.substring(start, end))
    }

    private fun parseColor(hex: String): Int =
        (hex.removePrefix("#").toLong(16) or 0xFF000000L).toInt()
}

fun markdownAnnotatedString(markdown: String): AnnotatedString = buildAnnotatedString {
    MarkdownParser.blocks(markdown).forEachIndexed { index, block ->
        if (index > 0) append("\n\n")
        withStyle(blockStyle(block.kind)) {
            if (block.kind == MarkdownBlockKind.Bullet) append("• ")
            MarkdownParser.runs(block.text).forEach { run ->
                withStyle(
                    SpanStyle(
                        color = run.color?.let { ComposeColor(it) } ?: ComposeColor.Unspecified,
                        fontWeight = if (run.bold) FontWeight.Bold else null,
                        fontStyle = if (run.italic) FontStyle.Italic else null,
                        textDecoration = if (run.strike) TextDecoration.LineThrough else null,
                    ),
                ) {
                    append(run.text)
                }
            }
        }
    }
}

fun markdownSpanned(markdown: String): Spanned {
    val builder = SpannableStringBuilder()
    MarkdownParser.blocks(markdown).forEachIndexed { index, block ->
        if (index > 0) builder.append("\n\n")
        val start = builder.length
        if (block.kind == MarkdownBlockKind.Bullet) builder.append("• ")
        MarkdownParser.runs(block.text).forEach { run ->
            val runStart = builder.length
            builder.append(run.text)
            val runEnd = builder.length
            if (runEnd <= runStart) return@forEach
            if (run.bold) builder.setSpan(StyleSpan(Typeface.BOLD), runStart, runEnd, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
            if (run.italic) builder.setSpan(StyleSpan(Typeface.ITALIC), runStart, runEnd, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
            if (run.strike) builder.setSpan(StrikethroughSpan(), runStart, runEnd, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
            run.color?.let {
                builder.setSpan(ForegroundColorSpan(it), runStart, runEnd, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
            }
        }
        val end = builder.length
        if (end <= start) return@forEachIndexed
        when (block.kind) {
            MarkdownBlockKind.Heading1 -> {
                builder.setSpan(RelativeSizeSpan(1.6f), start, end, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
                builder.setSpan(StyleSpan(Typeface.BOLD), start, end, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
            }
            MarkdownBlockKind.Heading2 -> {
                builder.setSpan(RelativeSizeSpan(1.35f), start, end, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
                builder.setSpan(StyleSpan(Typeface.BOLD), start, end, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
            }
            MarkdownBlockKind.Heading3 -> {
                builder.setSpan(RelativeSizeSpan(1.18f), start, end, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
                builder.setSpan(StyleSpan(Typeface.BOLD), start, end, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
            }
            MarkdownBlockKind.Quote -> {
                builder.setSpan(ForegroundColorSpan(0xFF666666.toInt()), start, end, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
                builder.setSpan(StyleSpan(Typeface.ITALIC), start, end, Spannable.SPAN_EXCLUSIVE_EXCLUSIVE)
            }
            MarkdownBlockKind.Bullet, MarkdownBlockKind.Paragraph -> Unit
        }
    }
    return builder
}

private fun blockStyle(kind: MarkdownBlockKind): SpanStyle = when (kind) {
    MarkdownBlockKind.Heading1 -> SpanStyle(fontSize = 22.sp, fontWeight = FontWeight.Bold)
    MarkdownBlockKind.Heading2 -> SpanStyle(fontSize = 18.sp, fontWeight = FontWeight.Bold)
    MarkdownBlockKind.Heading3 -> SpanStyle(fontSize = 16.sp, fontWeight = FontWeight.Bold)
    MarkdownBlockKind.Quote -> SpanStyle(color = ComposeColor(0xFF666666), fontStyle = FontStyle.Italic)
    MarkdownBlockKind.Bullet, MarkdownBlockKind.Paragraph -> SpanStyle()
}
